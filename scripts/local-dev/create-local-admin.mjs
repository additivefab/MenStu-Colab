// Creates (or repairs) a LOCAL-ONLY superadmin test account in the local D1
// database used by `npm run dev`. Usage: `npm run dev:admin`.
//
// - Writes only to .wrangler/state (the same Miniflare state the dev server
//   and `npm run db:migrate:local` use). It never talks to a hosted database.
// - The password is generated randomly on first run and stored in the
//   gitignored file .local-dev-admin.txt (mode 0600). It is never printed.
// - Idempotent: later runs reuse the saved password and only touch the
//   database when the account is missing or no longer matches.
import { chmod, readFile, writeFile } from "node:fs/promises";
import { randomBytes } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Miniflare } from "miniflare";
import { hashPassword, passwordError, verifyPassword } from "../../lib/local-password.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const credentialFile = path.join(root, ".local-dev-admin.txt");
// Must match vite.config.ts (placeholder database_id) and wrangler.local.jsonc.
const LOCAL_DATABASE_ID = "00000000-0000-4000-8000-000000000000";
const USERNAME = "local-admin";
const OPEN_ID = "local-dev-only:superadmin";
const DISPLAY_NAME = "本地开发管理员";
const AUDIT_REQUEST_ID = "local-dev-admin:issue";

async function readSavedPassword() {
  let text;
  try {
    text = await readFile(credentialFile, "utf8");
  } catch (error) {
    if (error?.code === "ENOENT") return null;
    throw error;
  }
  const line = text.split(/\r?\n/).find((value) => value.startsWith("password="));
  const password = line?.slice("password=".length) ?? "";
  if (passwordError(password)) {
    throw new Error(`${path.basename(credentialFile)} has no usable password line; delete the file to generate a new local password.`);
  }
  return password;
}

async function saveCredentials(password) {
  const content = [
    "# LOCAL-ONLY development superadmin for the local D1 in .wrangler/state.",
    "# Generated by `npm run dev:admin`. Gitignored. Never reuse this password elsewhere.",
    "url=http://localhost:3000",
    `username=${USERNAME}`,
    `password=${password}`,
    "",
  ].join("\n");
  await writeFile(credentialFile, content, { encoding: "utf8", mode: 0o600 });
  await chmod(credentialFile, 0o600);
}

const mf = new Miniflare({
  modules: true,
  script: "export default { fetch() { return new Response(null, { status: 404 }); } };",
  compatibilityDate: "2025-09-01",
  d1Databases: { DB: LOCAL_DATABASE_ID },
  // Wrangler `--persist-to .wrangler/state` and the Cloudflare Vite plugin
  // both keep D1 under <state>/v3/d1.
  d1Persist: path.join(root, ".wrangler/state/v3/d1"),
});

try {
  const db = await mf.getD1Database("DB");
  const tables = await db.prepare(`SELECT name FROM sqlite_master WHERE type = 'table'
    AND name IN ('app_users', 'local_credentials', 'local_auth_events')`).all();
  if (tables.results.length !== 3) {
    throw new Error("Local database is not migrated. Run `npm run db:migrate:local` first.");
  }

  const savedPassword = await readSavedPassword();
  const password = savedPassword ?? randomBytes(24).toString("base64url");

  const usernameOwner = await db.prepare(`SELECT c.app_user_id, u.feishu_open_id FROM local_credentials c
    JOIN app_users u ON u.id = c.app_user_id WHERE c.username = ?`).bind(USERNAME).first();
  if (usernameOwner && usernameOwner.feishu_open_id !== OPEN_ID) {
    throw new Error(`Username ${USERNAME} already belongs to another local account; refusing to change it.`);
  }

  await db.prepare(`INSERT INTO app_users (feishu_open_id, display_name, role, student_id, active)
    VALUES (?, ?, 'superadmin', NULL, 1)
    ON CONFLICT(feishu_open_id) DO UPDATE SET role = 'superadmin', student_id = NULL, active = 1
    WHERE app_users.role != 'superadmin' OR app_users.student_id IS NOT NULL OR app_users.active != 1`)
    .bind(OPEN_ID, DISPLAY_NAME).run();
  const user = await db.prepare("SELECT id FROM app_users WHERE feishu_open_id = ?").bind(OPEN_ID).first();

  const credential = await db.prepare(`SELECT student_id, authorized_role, username, password_hash,
      must_change_password, activation_hash FROM local_credentials WHERE app_user_id = ?`).bind(user.id).first();
  const upToDate = credential
    && credential.student_id === null
    && credential.authorized_role === "superadmin"
    && credential.username === USERNAME
    && Number(credential.must_change_password) === 0
    && credential.activation_hash === null
    && await verifyPassword(password, credential.password_hash);

  if (!upToDate) {
    const passwordHash = await hashPassword(password);
    await db.batch([
      db.prepare(`INSERT INTO local_credentials
          (app_user_id, student_id, authorized_role, username, password_hash, must_change_password)
        VALUES (?, NULL, 'superadmin', ?, ?, 0)
        ON CONFLICT(app_user_id) DO UPDATE SET student_id = NULL, authorized_role = 'superadmin',
          username = excluded.username, password_hash = excluded.password_hash, must_change_password = 0,
          activation_hash = NULL, activation_expires_at = NULL, version = local_credentials.version + 1,
          updated_at = CURRENT_TIMESTAMP`)
        .bind(user.id, USERNAME, passwordHash),
      db.prepare(`INSERT INTO local_auth_events (app_user_id, actor_user_id, action, request_id)
        VALUES (?, ?, 'issue', ?) ON CONFLICT(request_id) DO NOTHING`)
        .bind(user.id, user.id, AUDIT_REQUEST_ID),
    ]);
  }
  if (!savedPassword || !upToDate) await saveCredentials(password);

  console.log(upToDate
    ? `Local superadmin "${USERNAME}" is already set up.`
    : `Local superadmin "${USERNAME}" is ready.`);
  console.log(`Credentials (local only): ${path.relative(process.cwd(), credentialFile) || credentialFile}`);
} finally {
  await mf.dispose();
}
